import React, { useEffect, useState } from 'react';
import {
  Animated,
  Pressable,
  ScrollView,
  StyleSheet,
  Text,
  View,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';

import { OnboardingHeader } from '@/components/onboarding/onboarding-header';
import { StickyContinueCard } from '@/components/onboarding/sticky-continue-card';
import { BrandTheme, MaxContentWidth } from '@/constants/theme';
import type { ConfidenceArea } from '@/domain/curriculum/types';
import { usePlanner } from '@/state/planner-context';

function CourseCategoryIcon({ subjectArea }: { subjectArea: ConfidenceArea }) {
  const isAnalytical =
    subjectArea === 'Science' ||
    subjectArea === 'Research' ||
    subjectArea === 'Mathematics';

  return (
    <View style={styles.courseIconCircle} aria-hidden>
      {isAnalytical ? (
        <View style={styles.targetIconOuter}>
          <View style={styles.targetIconInner} />
        </View>
      ) : (
        <View style={styles.leafIconShape}>
          <View style={styles.leafVeinLine} />
        </View>
      )}
    </View>
  );
}

/**
 * Screen 11 — Recommended Schedule (`11_Recommended_Schedule.png`)
 *
 * Displays the next-semester course schedule generated by `schedule-generator.ts`:
 * - Semester header card with total recommended units and Mamdani Stress badge
 * - List of recommended courses with category icons, titles, unit counts, and
 *   transparent placement explanations (`reason`)
 * - Continues to the main application Plan / Roadmap tab (`/(tabs)/plan`)
 */
export default function RecommendedScheduleScreen() {
  const router = useRouter();
  const { academicPlan, completeOnboardingAndPersistPlan } = usePlanner();
  const { nextSemester } = academicPlan;
  const [expandedCode, setExpandedCode] = useState<string | null>(null);

  const isTest = Boolean(process.env.JEST_WORKER_ID);
  const [fadeAnim] = useState(() => new Animated.Value(isTest ? 1 : 0));

  useEffect(() => {
    if (isTest) return;
    Animated.timing(fadeAnim, {
      toValue: 1,
      duration: 380,
      useNativeDriver: true,
    }).start();
  }, [fadeAnim, isTest]);

  const handleContinue = async () => {
    await completeOnboardingAndPersistPlan();
    router.push('/(tabs)/plan');
  };

  return (
    <SafeAreaView style={styles.safeArea} edges={['top', 'bottom']}>
      <Animated.View style={[styles.mainColumn, { opacity: fadeAnim }]}>
        <OnboardingHeader
          stepText="STEP 3 OF 3"
          sectionText="YOUR PLAN"
          progressPercent={100}
          title="Recommended Schedule"
          subtitle={'Here are the courses suggested for your next\nsemester.'}
        />

        <ScrollView
          style={styles.scrollArea}
          contentContainerStyle={styles.scrollContent}
          showsVerticalScrollIndicator={false}>
          {/* Semester Summary Card */}
          <View style={styles.semesterSummaryCard} testID="recommended-semester-card">
            <View style={styles.semesterSummaryLeft}>
              <Text style={styles.semesterTitle} testID="recommended-semester-title">
                {nextSemester.semesterTitle}
              </Text>
              <Text style={styles.semesterSubtitle} testID="recommended-units-summary">
                {`Total: ${nextSemester.totalUnits} of ${nextSemester.recommendedUnitLimit} recommended units`}
              </Text>
            </View>
            <View style={styles.stressBadge}>
              <Text style={styles.stressBadgeText} testID="recommended-stress-badge">
                {`Stress: ${nextSemester.stressScore}%`}
              </Text>
            </View>
          </View>

          {/* Recommended Courses List */}
          <View style={styles.courseListContainer}>
            {nextSemester.courses.map((item) => {
              const isExpanded = expandedCode === item.course.code;
              const unitText =
                item.course.units === 1 ? '1 unit' : `${item.course.units} units`;
              const isLowStress = item.courseStressLabel === 'Low';
              const isHighStress =
                item.courseStressLabel === 'High' ||
                item.courseStressLabel === 'Very High';

              return (
                <Pressable
                  key={item.course.code}
                  accessibilityRole="button"
                  testID={`recommended-course-${item.course.code}`}
                  onPress={() =>
                    setExpandedCode((prev) =>
                      prev === item.course.code ? null : item.course.code
                    )
                  }
                  style={styles.courseItemWrapper}>
                  <View style={styles.courseRow}>
                    <CourseCategoryIcon subjectArea={item.subjectArea} />
                    <View style={styles.courseMainInfo}>
                      <View style={styles.courseCodeHeaderRow}>
                        <Text style={styles.courseCodeText}>{item.course.code}</Text>
                        <View
                          style={[
                            styles.courseStressPill,
                            isLowStress
                              ? styles.courseStressPillLow
                              : isHighStress
                                ? styles.courseStressPillHigh
                                : styles.courseStressPillMod,
                          ]}>
                          <Text
                            style={[
                              styles.courseStressPillText,
                              isLowStress
                                ? styles.courseStressTextLow
                                : isHighStress
                                  ? styles.courseStressTextHigh
                                  : styles.courseStressTextMod,
                            ]}>
                            {`${item.courseStressLabel} Stress`}
                          </Text>
                        </View>
                      </View>
                      <Text style={styles.courseTitleText}>{item.course.title}</Text>
                      <Text style={styles.whyThisCoursePrompt}>
                        {isExpanded
                          ? 'Hide why this course ▲'
                          : 'Why this course? ▼'}
                      </Text>
                    </View>
                    <Text style={styles.courseUnitText}>{unitText}</Text>
                  </View>

                  {isExpanded && (
                    <View
                      style={styles.reasonBanner}
                      testID={`placement-reason-${item.course.code}`}>
                      <Text style={styles.reasonHeading}>
                        Why this course was placed in your schedule:
                      </Text>
                      <Text style={styles.reasonText}>{item.reason}</Text>
                      <Text style={styles.reasonMetaText}>
                        {`Prerequisite Tier ${item.tier} · ${item.subjectArea} (Difficulty ${item.difficultyScore}/10 · Stress ${item.courseStressScore}%)`}
                      </Text>
                    </View>
                  )}
                </Pressable>
              );
            })}
          </View>
        </ScrollView>

        <StickyContinueCard
          caption={'Review the recommended courses for your next\nterm.'}
          buttonLabel="Continue"
          testID="recommended-schedule-continue"
          onPress={handleContinue}
        />
      </Animated.View>
    </SafeAreaView>
  );
}

